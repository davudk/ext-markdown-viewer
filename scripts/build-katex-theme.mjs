/**
 * Regenerates `entrypoints/katex-theme.css` and `public/fonts/` from the
 * installed katex package. Run after bumping katex; the two outputs are
 * committed, because a build step that reaches into node_modules for 20 binary
 * files is a worse thing to debug than a checked-in artefact.
 *
 * KaTeX's own stylesheet cannot be used as shipped: its `@font-face` rules
 * point at `fonts/` relative to themselves, and in a packed extension the
 * stylesheet ends up in `assets/` while the fonts have to sit somewhere
 * web-accessible. Everything this script does follows from that.
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'node_modules/katex/dist';
const FONT_OUT = 'public/fonts';
const CSS_OUT = 'entrypoints/katex-theme.css';

mkdirSync(FONT_OUT, { recursive: true });
const woff2 = readdirSync(join(SRC, 'fonts')).filter((file) => file.endsWith('.woff2'));
for (const name of woff2) copyFileSync(join(SRC, 'fonts', name), join(FONT_OUT, name));

/**
 * What each KaTeX face degrades to when its woff2 does not load. Without one,
 * the browser falls back to whatever it uses for an unknown family — usually
 * the page's sans — and a formula in the wrong metrics is barely readable.
 */
const FALLBACK = [
  ['KaTeX_Typewriter', `"Courier New",Courier,monospace`],
  ['KaTeX_SansSerif', `Helvetica,Arial,sans-serif`],
  ['KaTeX_Script', `cursive,serif`],
  ['KaTeX_Caligraphic', `cursive,serif`],
  ['KaTeX_Fraktur', `"Times New Roman",Times,serif`],
  ['KaTeX_Math', `"Times New Roman",Times,serif`],
  ['KaTeX_AMS', `"Times New Roman",Times,serif`],
  ['KaTeX_Main', `"Times New Roman",Times,serif`],
  ['KaTeX_Size', `"Times New Roman",Times,serif`],
];

function fallbackFor(family) {
  const hit = FALLBACK.find(([prefix]) => family.startsWith(prefix));
  return hit ? hit[1] : 'serif';
}

const css = readFileSync(join(SRC, 'katex.min.css'), 'utf8');

// Split into @font-face blocks and everything else: the two need opposite
// treatment, since `font-family` inside a face declares the name rather than
// using it, and appending a fallback there would be invalid.
const parts = css.split(/(@font-face\{[^}]*\})/g).filter(Boolean);

let faces = 0;
const rewritten = parts
  .map((part) => {
    if (!part.startsWith('@font-face{')) {
      return part.replace(
        /font-family:(KaTeX_[A-Za-z0-9]+)/g,
        (_, family) => `font-family:${family},${fallbackFor(family)}`,
      );
    }

    faces += 1;
    return (
      part
        // woff2 only: every browser this extension runs in supports it, and the
        // .ttf and .woff twins would triple the packaged size for nothing.
        .replace(/src:[^;}]*/, (src) => {
          const file = /fonts\/([\w-]+)\.woff2/.exec(src)?.[1];
          if (!file) throw new Error(`no woff2 in: ${src}`);
          return `src:url(../fonts/${file}.woff2) format("woff2")`;
        })
        // `block` hides the glyphs for three seconds before conceding to the
        // fallback; `swap` shows it immediately. The files are local, so the
        // swap is invisible in the normal case and everything in the broken one.
        .replace('font-display:block', 'font-display:swap')
    );
  })
  .join('');

const version = JSON.parse(readFileSync('node_modules/katex/package.json', 'utf8')).version;

const HEADER = `/* Markdown Viewer — KaTeX stylesheet for the math add-on.

   GENERATED by scripts/build-katex-theme.mjs from katex ${version}. Do not edit;
   rerun the script. It makes three changes to katex.min.css:

     1. Every @font-face src is reduced to its .woff2 and repointed at
        ../fonts/. The path is relative to where this file lands in the build
        output (assets/katex-theme.css), so it resolves to
        chrome-extension://<id>/fonts/<name>.woff2 — the fonts are packaged and
        the extension never asks the network for anything. They must be listed
        in web_accessible_resources as \`fonts/*.woff2\`, or the page the CSS is
        injected into is not permitted to load them.
     2. font-display: block -> swap, so a font that fails to load costs a change
        of typeface rather than three seconds of invisible formulae.
     3. A generic fallback family is appended to every font-family naming a
        KaTeX face, so that same failure lands somewhere legible.

   Everything after the KaTeX rules is ours. */

`;

const OURS = `

/* ==========================================================================
   Markdown Viewer additions
   ========================================================================== */

/* A display equation is one long unbreakable line; the measure is not. Let it
   scroll inside its own box rather than pushing the whole document sideways.
   \`overflow-y\` is pinned because a lone \`overflow-x: auto\` computes the other
   axis to \`auto\` as well, which clips the parts of a formula that sit above
   and below the line box. */
.katex-display {
  overflow-x: auto;
  overflow-y: hidden;
  padding: 0.5em 0;
}

/* Set by the add-on on the ones that actually overflow, so a scroll box is
   reachable without a mouse. */
.katex-display[tabindex]:focus-visible {
  outline: 2px solid var(--mdv-accent, #0a53be);
  outline-offset: 2px;
  border-radius: var(--mdv-radius-sm, 4px);
}

/* KaTeX writes \`color: #cc0000\` inline on a formula it could not parse, which
   is unreadable on the dark theme. Overriding an inline style is the one thing
   !important is for. */
.katex-error {
  color: var(--mdv-tk-deletion, #b3202c) !important;
  font-family: var(--mdv-font-mono, ui-monospace, monospace);
  font-size: 0.9em;
  white-space: pre-wrap;
}
`;

const out = HEADER + rewritten.trim() + OURS;
writeFileSync(CSS_OUT, out);

const remote = out.match(/url\((?!\.\.\/fonts\/)[^)]*\)/g) ?? [];
if (remote.length > 0) throw new Error(`non-local url(): ${remote.join(', ')}`);

console.log(
  `✔ ${CSS_OUT} (${out.length} bytes, ${faces} faces) and ${woff2.length} woff2 files from katex ${version}`,
);
